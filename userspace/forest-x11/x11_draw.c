static inline void put_pixel(uint8_t* surf, int sw, int sh, int x, int y, uint32_t c) {
    if (x < 0 || y < 0 || x >= sw || y >= sh) return;
    uint32_t* px = (uint32_t*)(surf + (y * sw + x) * 4);
    uint32_t srca = (c >> 24) & 0xFF;
    if (srca == 0) return;
    if (srca == 255) { *px = c; return; }
    uint32_t dst = *px;
    uint32_t da = (dst >> 24) & 0xFF;
    uint32_t dr = (dst >> 16) & 0xFF;
    uint32_t dg = (dst >> 8) & 0xFF;
    uint32_t db = dst & 0xFF;
    uint32_t sr = (c >> 16) & 0xFF;
    uint32_t sg = (c >> 8) & 0xFF;
    uint32_t sb = c & 0xFF;
    uint32_t a = srca;
    uint32_t ia = 255 - a;
    uint32_t r = (sr * a + dr * ia) / 255;
    uint32_t g = (sg * a + dg * ia) / 255;
    uint32_t b = (sb * a + db * ia) / 255;
    uint32_t na = a + (da * ia) / 255;
    *px = (na << 24) | (r << 16) | (g << 8) | b;
}

void x11_draw_rect(uint8_t* surf, int sw, int sh, int x, int y, int w, int h,
                   uint32_t color) {
    for (int j = y; j < y + h; j++)
        for (int i = x; i < x + w; i++)
            put_pixel(surf, sw, sh, i, j, color);
}

void x11_draw_hline(uint8_t* surf, int sw, int sh, int x, int y, int w,
                    uint32_t color) {
    for (int i = x; i < x + w; i++)
        put_pixel(surf, sw, sh, i, y, color);
}

void x11_draw_vline(uint8_t* surf, int sw, int sh, int x, int y, int h,
                    uint32_t color) {
    for (int j = y; j < y + h; j++)
        put_pixel(surf, sw, sh, x, j, color);
}

void x11_draw_line(uint8_t* surf, int sw, int sh, int x0, int y0, int x1, int y1,
                   uint32_t color) {
    int dx = x1 > x0 ? x1 - x0 : x0 - x1;
    int dy = y1 > y0 ? y1 - y0 : y0 - y1;
    int sx = x0 < x1 ? 1 : -1;
    int sy = y0 < y1 ? 1 : -1;
    int err = dx - dy;
    for (;;) {
        put_pixel(surf, sw, sh, x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx) { err += dx; y0 += sy; }
    }
}

void x11_draw_circle(uint8_t* surf, int sw, int sh, int cx, int cy, int r,
                     uint32_t color, int filled) {
    int x = r, y = 0, d = 1 - r;
    while (x >= y) {
        if (filled) {
            x11_draw_hline(surf, sw, sh, cx - x, cy + y, 2 * x + 1, color);
            x11_draw_hline(surf, sw, sh, cx - x, cy - y, 2 * x + 1, color);
            x11_draw_hline(surf, sw, sh, cx - y, cy + x, 2 * y + 1, color);
            x11_draw_hline(surf, sw, sh, cx - y, cy - x, 2 * y + 1, color);
        } else {
            put_pixel(surf, sw, sh, cx + x, cy + y, color);
            put_pixel(surf, sw, sh, cx - x, cy + y, color);
            put_pixel(surf, sw, sh, cx + x, cy - y, color);
            put_pixel(surf, sw, sh, cx - x, cy - y, color);
            put_pixel(surf, sw, sh, cx + y, cy + x, color);
            put_pixel(surf, sw, sh, cx - y, cy + x, color);
            put_pixel(surf, sw, sh, cx + y, cy - x, color);
            put_pixel(surf, sw, sh, cx - y, cy - x, color);
        }
        y++;
        if (d <= 0) { d += 2 * y + 1; }
        else { x--; d += 2 * (y - x) + 1; }
    }
}

void x11_draw_arc(uint8_t* surf, int sw, int sh, int cx, int cy, int rx, int ry,
                  int angle1, int angle2, uint32_t color) {
    (void)rx; (void)ry;
    int steps = 64;
    int a1 = angle1 * 64 / 360;
    int a2 = angle2 * 64 / 360;
    int prev_x = -1, prev_y = -1;
    for (int i = a1; i <= a2; i++) {
        int a = i * 360 / 64;
        int px = cx + (rx * a) / 360;
        int py = cy - (ry * a) / 360;
        if (prev_x >= 0)
            x11_draw_line(surf, sw, sh, prev_x, prev_y, px, py, color);
        prev_x = px;
        prev_y = py;
    }
}

