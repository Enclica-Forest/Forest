void x11_draw_text(uint8_t* surf, int sw, int sh, int x, int y,
                   const char* text, int len, uint32_t color, int font_h) {
    (void)font_h;
    for (int i = 0; i < len; i++) {
        unsigned char ch = (unsigned char)text[i];
        if (ch < 32 || ch > 126) ch = 32;
        for (int row = 0; row < 8; row++) {
            uint8_t bits = font8x8[ch][row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80 >> col))
                    put_pixel(surf, sw, sh, x + i * 8 + col, y + row, color);
            }
        }
    }
}

void x11_put_image(uint8_t* surf, int sw, int sh, int x, int y, int w, int h,
                   const uint8_t* data, int depth) {
    (void)depth;
    for (int j = 0; j < h; j++) {
        for (int i = 0; i < w; i++) {
            int si = (j * w + i) * 4;
            uint32_t c = 0;
            c |= (uint32_t)data[si + 0] << 0;
            c |= (uint32_t)data[si + 1] << 8;
            c |= (uint32_t)data[si + 2] << 16;
            c |= (uint32_t)data[si + 3] << 24;
            put_pixel(surf, sw, sh, x + i, y + j, c);
        }
    }
}

void x11_copy_area(uint8_t* dst, int dw, int dh, int dx, int dy,
                   const uint8_t* src, int sw, int sh, int sx, int sy, int w, int h) {
    (void)dh;
    for (int j = 0; j < h; j++) {
        for (int i = 0; i < w; i++) {
            int sx2 = sx + i, sy2 = sy + j;
            int dx2 = dx + i, dy2 = dy + j;
            if (sx2 < 0 || sy2 < 0 || sx2 >= sw || sy2 >= sh) continue;
            if (dx2 < 0 || dy2 < 0 || dx2 >= dw || dy2 >= dh) continue;
            uint32_t c = ((uint32_t*)src)[sy2 * sw + sx2];
            ((uint32_t*)dst)[dy2 * dw + dx2] = c;
        }
    }
}

void x11_fill_polygon(uint8_t* surf, int sw, int sh, const int* pts, int npts,
                      uint32_t color) {
    if (npts < 3) return;
    int min_y = pts[1], max_y = pts[1];
    for (int i = 1; i < npts; i++) {
        if (pts[i * 2 + 1] < min_y) min_y = pts[i * 2 + 1];
        if (pts[i * 2 + 1] > max_y) max_y = pts[i * 2 + 1];
    }
    if (min_y < 0) min_y = 0;
    if (max_y >= sh) max_y = sh - 1;
    for (int y = min_y; y <= max_y; y++) {
        int nodes[64], node_count = 0;
        int j = npts - 1;
        for (int i = 0; i < npts; i++) {
            int yi = pts[i * 2 + 1], yj = pts[j * 2 + 1];
            if ((yi < y && yj >= y) || (yj < y && yi >= y)) {
                if (node_count < 64)
                    nodes[node_count++] = pts[i * 2] + (y - yi) *
                        (pts[j * 2] - pts[i * 2]) / (yj - yi);
            }
            j = i;
        }
        for (int i = 0; i < node_count - 1; i++)
            for (int k = i + 1; k < node_count; k++)
                if (nodes[i] > nodes[k]) { int t = nodes[i]; nodes[i] = nodes[k]; nodes[k] = t; }
        for (int i = 0; i < node_count - 1; i += 2) {
            if (nodes[i] >= sw) break;
            if (nodes[i + 1] < 0) continue;
            int x0 = nodes[i] < 0 ? 0 : nodes[i];
            int x1 = nodes[i + 1] >= sw ? sw - 1 : nodes[i + 1];
            x11_draw_hline(surf, sw, sh, x0, y, x1 - x0 + 1, color);
        }
    }
}
