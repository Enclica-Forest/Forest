graphics_result_t enhanced_cursor_init(void) {
    debuglog(DEBUG_INFO, "Initializing enhanced cursor subsystem...\n");
    
    g_active_cursor = NULL;
    
    return GRAPHICS_SUCCESS;
}

graphics_result_t enhanced_cursor_shutdown(void) {
    if (g_active_cursor) {
        enhanced_cursor_destroy(g_active_cursor);
        g_active_cursor = NULL;
    }
    
    debuglog(DEBUG_INFO, "Enhanced cursor subsystem shutdown complete\n");
    return GRAPHICS_SUCCESS;
}

graphics_result_t enhanced_cursor_create(cursor_type_t type,
                                      const cursor_theme_t* theme,
                                      enhanced_cursor_t** cursor) {
    if (!cursor) {
        return GRAPHICS_ERROR_INVALID_PARAMETER;
    }
    
    enhanced_cursor_t* cur = kmalloc(sizeof(enhanced_cursor_t));
    if (!cur) {
        return GRAPHICS_ERROR_OUT_OF_MEMORY;
    }
    
    memset(cur, 0, sizeof(enhanced_cursor_t));
    
    cur->type = type;
    cur->state = CURSOR_STATE_IDLE;
    cur->x = 0;
    cur->y = 0;
    cur->prev_x = 0;
    cur->prev_y = 0;
    cur->visible = true;
    cur->animated = false;
    cur->animation_frame = 0;
    cur->last_animation_time = 0;
    
    cur->primary_color = theme ? theme->primary : COLOR_WHITE;
    cur->secondary_color = theme ? theme->secondary : COLOR_BLACK;
    
    cur->hotspot_x = CURSOR_HOTSPOT_X;
    cur->hotspot_y = CURSOR_HOTSPOT_Y;
    
    cur->shadow.enabled = true;
    cur->shadow.blur_radius = 3;
    cur->shadow.offset_x = 2;
    cur->shadow.offset_y = 2;
    cur->shadow.alpha = 0.4f;
    
    cur->smooth.enabled = true;
    cur->smooth.scale = 1.0f;
    
    graphics_result_t result = graphics_create_surface(
        CURSOR_WIDTH, CURSOR_HEIGHT, PIXEL_FORMAT_RGBA_8888, &cur->surface);
    if (result != GRAPHICS_SUCCESS) {
        kfree(cur);
        return result;
    }
    
    result = graphics_create_surface(
        CURSOR_WIDTH + 10, CURSOR_HEIGHT + 10, PIXEL_FORMAT_RGBA_8888, &cur->shadow_surface);
    if (result != GRAPHICS_SUCCESS) {
        graphics_destroy_surface(cur->surface);
        kfree(cur);
        return result;
    }
    
    *cursor = cur;
    
    return enhanced_cursor_set_type(cur, type);
}

graphics_result_t enhanced_cursor_destroy(enhanced_cursor_t* cursor) {
    if (!cursor) {
        return GRAPHICS_SUCCESS;
    }
    
    if (cursor->surface) {
        graphics_destroy_surface(cursor->surface);
        cursor->surface = NULL;
    }
    
    if (cursor->shadow_surface) {
        graphics_destroy_surface(cursor->shadow_surface);
        cursor->shadow_surface = NULL;
    }
    
    kfree(cursor);
    
    return GRAPHICS_SUCCESS;
}

static graphics_result_t render_cursor_bitmap(const uint8_t* bitmap,
                                          graphics_surface_t* surface,
                                          graphics_color_t primary,
                                          graphics_color_t secondary,
                                          graphics_color_t outline) {
    if (!surface || !bitmap || !surface->pixels) {
        return GRAPHICS_ERROR_INVALID_PARAMETER;
    }
    
    uint32_t primary_pixel = (primary.a << 24) | (primary.r << 16) |
                            (primary.g << 8) | primary.b;
    (void)secondary;
    uint32_t outline_pixel = (outline.a << 24) | (outline.r << 16) |
                           (outline.g << 8) | outline.b;
    
    for (uint32_t y = 0; y < CURSOR_HEIGHT; y++) {
        for (uint32_t x = 0; x < CURSOR_WIDTH; x++) {
            uint8_t val = bitmap[y * CURSOR_WIDTH + x];
            uint32_t* pixel = (uint32_t*)(
                (uint8_t*)surface->pixels + y * surface->pitch + x * 4);
            
            if (val == 0) {
                *pixel = 0x00000000;
            }
            else if (val == 1) {
                *pixel = outline_pixel;
            }
            else {
                *pixel = primary_pixel;
            }
        }
    }
    
    return GRAPHICS_SUCCESS;
}

