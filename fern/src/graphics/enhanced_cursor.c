graphics_result_t enhanced_cursor_set_state(enhanced_cursor_t* cursor, cursor_state_t state) {
    if (!cursor) {
        return GRAPHICS_ERROR_INVALID_PARAMETER;
    }
    
    cursor->state = state;
    
    if (state == CURSOR_STATE_BUSY) {
        cursor->animated = true;
    }
    else if (state == CURSOR_STATE_IDLE) {
        cursor->animated = false;
    }
    
    return GRAPHICS_SUCCESS;
}

