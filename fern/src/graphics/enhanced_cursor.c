graphics_result_t enhanced_cursor_draw(enhanced_cursor_t* cursor, graphics_surface_t* surface) {
    if (!cursor || !surface || !cursor->visible) {
        return GRAPHICS_ERROR_INVALID_PARAMETER;
    }
    
    int32_t draw_x = cursor->x - cursor->hotspot_x;
    int32_t draw_y = cursor->y - cursor->hotspot_y;
    
    if (cursor->shadow.enabled && cursor->shadow_surface) {
        int32_t shadow_x = draw_x + cursor->shadow.offset_x;
        int32_t shadow_y = draw_y + cursor->shadow.offset_y;
        
        uint8_t alpha = (uint8_t)(cursor->shadow.alpha * 255);
        
        for (uint32_t y = 0; y < CURSOR_HEIGHT; y++) {
            for (uint32_t x = 0; x < CURSOR_WIDTH; x++) {
                uint32_t* src_pix = (uint32_t*)(
                    (uint8_t*)cursor->surface->pixels + y * cursor->surface->pitch + x * 4);
                
                if ((*src_pix & 0xFF000000) == 0) {
                    continue;
                }
                
                uint32_t* shadow_pix = (uint32_t*)(
                    (uint8_t*)cursor->shadow_surface->pixels + y * cursor->shadow_surface->pitch + x * 4);
                
                uint32_t pixel = *src_pix;
                uint8_t r = (pixel >> 16) & 0xFF;
                uint8_t g = (pixel >> 8) & 0xFF;
                uint8_t b = pixel & 0xFF;
                
                *shadow_pix = (alpha << 24) | (r << 16) | (g << 8) | b;
            }
        }
        
        graphics_rect_t shadow_rect = {shadow_x, shadow_y,
                                     CURSOR_WIDTH + 5, CURSOR_HEIGHT + 5};
        graphics_blit_surface(cursor->shadow_surface, &shadow_rect,
                           shadow_x, shadow_y);
    }
    
    graphics_rect_t src_rect = {0, 0, CURSOR_WIDTH, CURSOR_HEIGHT};
    graphics_result_t result = graphics_blit_surface(cursor->surface, &src_rect,
                                                   draw_x, draw_y);
    
    return result;
}

graphics_result_t enhanced_cursor_update(enhanced_cursor_t* cursor, uint64_t current_time_ms) {
    if (!cursor || !cursor->animated) {
        return GRAPHICS_SUCCESS;
    }
    
    if (current_time_ms - cursor->last_animation_time >= CURSOR_ANIMATION_SPEED_MS) {
        cursor->animation_frame = (cursor->animation_frame + 1) % CURSOR_ANIMATION_FRAMES;
        cursor->last_animation_time = current_time_ms;
    }
    
    return GRAPHICS_SUCCESS;
}

graphics_result_t enhanced_cursor_animate(enhanced_cursor_t* cursor, bool enable) {
    if (!cursor) {
        return GRAPHICS_ERROR_INVALID_PARAMETER;
    }
    
    cursor->animated = enable;
    if (enable) {
        cursor->animation_frame = 0;
    }
    
    return GRAPHICS_SUCCESS;
}

graphics_result_t enhanced_cursor_set_custom_bitmap(enhanced_cursor_t* cursor,
                                              const uint8_t* bitmap,
                                              uint32_t width,
                                              uint32_t height,
                                              int32_t hotspot_x,
                                              int32_t hotspot_y) {
    if (!cursor || !bitmap || width == 0 || height == 0) {
        return GRAPHICS_ERROR_INVALID_PARAMETER;
    }
    
    if (width > CURSOR_WIDTH || height > CURSOR_HEIGHT) {
        return GRAPHICS_ERROR_INVALID_PARAMETER;
    }
    
    graphics_color_t outline = COLOR_BLACK;
    
    uint32_t primary_pixel = (cursor->primary_color.a << 24) |
                            (cursor->primary_color.r << 16) |
                            (cursor->primary_color.g << 8) |
                            cursor->primary_color.b;
    uint32_t outline_pixel = (outline.a << 24) | (outline.r << 16) |
                           (outline.g << 8) | outline.b;
    
    for (uint32_t y = 0; y < height; y++) {
        for (uint32_t x = 0; x < width; x++) {
            uint8_t val = bitmap[y * width + x];
            uint32_t* pixel = (uint32_t*)(
                (uint8_t*)cursor->surface->pixels + y * cursor->surface->pitch + x * 4);
            
            if (val == 0) {
                *pixel = 0x00000000;
            }
            else if (val == 1) {
                *pixel = outline_pixel;
            }
            else {
                *pixel = primary_pixel;
            }
        }
    }
    
    cursor->type = CURSOR_TYPE_CUSTOM;
    cursor->hotspot_x = hotspot_x;
    cursor->hotspot_y = hotspot_y;
    cursor->animated = false;
    
    return GRAPHICS_SUCCESS;
}

